#include "setup.hpp"
void main_setup() { // auto-generated by export_fluidx3d.m (dx=2.0mm, dt=6.40e-06s)
	LBM lbm(300u, 173u, 116u, 0.010000f); // grid + lattice viscosity
	const uint Nx=lbm.get_Nx(), Ny=lbm.get_Ny(), Nz=lbm.get_Nz();
	// ---- read voxel file: 0=fluid 1=wall 2=test object (x-fastest order) ----
	uchar* raw = new uchar[lbm.get_N()];
	{ FILE* f=fopen("windtunnel.raw","rb");
	  if(!f) { print_error("windtunnel.raw not found"); exit(1); }
	  if(fread(raw, 1, lbm.get_N(), f)!=lbm.get_N()) { print_error("raw size mismatch"); exit(1); } fclose(f); }
	parallel_for(lbm.get_N(), [&](ulong n) {
		lbm.flags[n] = raw[n]==0u ? 0u : (raw[n]==2u ? (TYPE_S|TYPE_X) : TYPE_S); // 流体=0(默认), 测试物=S|X 单独标记
	});
	// ---- inlet x=0 / outlet x=Nx-1: equilibrium boundaries ----
	parallel_for(lbm.get_N(), [&](ulong n) { uint x=0u, y=0u, z=0u; lbm.coordinates(n, x, y, z);
		if(x==0u)          { lbm.flags[n]=TYPE_E; lbm.rho[n]=1.0f; lbm.u.x[n]=0.08000f; lbm.u.y[n]=0.0f; lbm.u.z[n]=0.0f; }
		if(x==Nx-1u)       { lbm.flags[n]=TYPE_E; lbm.rho[n]=1.0f; lbm.u.x[n]=0.08000f; lbm.u.y[n]=0.0f; lbm.u.z[n]=0.0f; } // outlet: moving reservoir
	});
	// ---- 入口合成湍流 + 逐步时均/湍流度统计 + 力时程 ----
	const float uLx = 0.08000f, velPhys = 312.5000f; // 晶格来流 / 晶格->物理速度
	const float tuInl = 0.00464f; // 入口合成湍流度 (Tu 链: 蜂窝器+纱网+收缩段衰减)
	const ulong nAvgStart = 15000u; // 时均起点步 (剔除初始瞬态)
	const ulong Ncell = lbm.get_N();
	float* uSum = new float[3u*Ncell]();  float* u2Sum = new float[3u*Ncell](); // sum(u), sum(u^2), SoA: [c*Ncell+n]
	float* slBuf = new float[3u*Ncell]; // 切片流暂存 (与 uSum 同源读取路径, 时均块内采样)
	ulong nAvg = 0ull;  uint rngS = 987654321u;
	auto rnd01 = [&]() { rngS^=rngS<<13u; rngS^=rngS>>17u; rngS^=rngS<<5u; return (float)(rngS&0xFFFFFFu)/16777216.0f; };
	auto writeVTK = [&](const string& fname, const float* data, const uint ncomp) { // 大端 VTK (与 FluidX3D 输出同格式)
		FILE* f = fopen(fname.c_str(), "wb");  if(!f) { print_error("cannot write "+fname); return; }
		char hdr[512];
		sprintf(hdr, "# vtk DataFile Version 3.0\nWindTunnel3D %s\nBINARY\nDATASET STRUCTURED_POINTS\nDIMENSIONS %u %u %u\nORIGIN %.8E %.8E %.8E\nSPACING 1.00000000 1.00000000 1.00000000\nPOINT_DATA %llu\nSCALARS data float %u\nLOOKUP_TABLE default\n", fname.c_str(), Nx, Ny, Nz, -0.5*(double)(Nx-1u), -0.5*(double)(Ny-1u), -0.5*(double)(Nz-1u), (unsigned long long)Ncell, ncomp);
		fputs(hdr, f);
		float* buf = new float[Ncell*ncomp];
		parallel_for(Ncell*ncomp, [&](ulong n) { union { float f; unsigned int u; } v; v.f = data[n]; v.u = (v.u>>24u)|((v.u>>8u)&0xFF00u)|((v.u<<8u)&0xFF0000u)|(v.u<<24u); buf[n] = v.f; }); // 字节序翻转 (VTK 经典二进制为大端)
		fwrite(buf, 4u*Ncell*ncomp, 1u, f);  fclose(f);  delete[] buf;
		print_info("File \""+fname+"\" saved.");
	};
	auto gustUpdate = [&]() { // 入口合成湍流: 流函数法 y-z 面横向涡旋脉动 (严格无散, 可输运到下游)
		float ky[6], kz[6], ph[6];  float sky=0.0f, skz=0.0f;
		for(uint q=0u; q<6u; q++) {
			ky[q] = 6.2831853f*(rnd01()<0.5f?-1.0f:1.0f)/(20.0f+60.0f*rnd01()); // 波长 20~80 格 (大涡, 抗耗散)
			kz[q] = 6.2831853f*(rnd01()<0.5f?-1.0f:1.0f)/(20.0f+60.0f*rnd01());
			ph[q] = 6.2831853f*rnd01();
			sky += ky[q]*ky[q];  skz += kz[q]*kz[q];
		}
		const float Ay = tuInl*uLx*sqrtf(2.0f/skz), Az = tuInl*uLx*sqrtf(2.0f/sky); // 精确归一: 每分量 rms = tuInl*uLx
		for(uint z=0u; z<Nz; z++) for(uint y=0u; y<Ny; y++) {
			const ulong n = (z*(ulong)Ny+(ulong)y)*(ulong)Nx;
			float gy=0.0f, gz=0.0f;
			for(uint m=0u; m<6u; m++) { const float sy=(float)y, sz=(float)z, cs=cosf(ky[m]*sy+kz[m]*sz+ph[m]);
				gy += kz[m]*cs;  gz += -ky[m]*cs; } // psi=sum sin, u=(dpsi/dz, -dpsi/dy): div-free
			lbm.u.x[n] = uLx;  lbm.u.y[n] = Ay*gy;  lbm.u.z[n] = Az*gz;
		}
		lbm.u.write_to_device();
	};
	{ FILE* fc=fopen("forces.csv","w"); fprintf(fc, "t_lattice,Fx,Fy,Fz\n"); fclose(fc); }
	const float Fscale = 0.470312f; // lattice -> Newton  (rho*dx^4/dt^2)
	const float Tscale = 6.400000e-06f; // lattice step -> seconds
	gustUpdate(); // 首个入口脉动 (run() 首次调用时以此初始化流场)
	for(uint s=0u; s<30000u; s+=1500u) {
		for(uint ss=0u; ss<1500u; ss+=100u) { // 力采样+入口湍流相位更新: 每 100 步 (涡脱 Nyquist, 与 VTK 解耦)
			gustUpdate();
			lbm.run(100u, 30000u);
			lbm.update_force_field();
			const float3 F = lbm.object_force(TYPE_S|TYPE_X); // 仅测试物 (整字节匹配)
			{ FILE* fc=fopen("forces.csv","a"); fprintf(fc, "%u,%g,%g,%g\n", lbm.get_t(), F.x*Fscale, F.y*Fscale, F.z*Fscale); fclose(fc); }
			if(lbm.get_t()>=nAvgStart) { // 逐步时均累加 (无欠采样) + 切片流采样 (与 uSum 同一 parallel_for 读取路径, 已由 mean_u 验证)
				lbm.u.read_from_device();
				parallel_for(Ncell, [&](ulong n) { const float ux=lbm.u.x[n], uy=lbm.u.y[n], uz=lbm.u.z[n];
					uSum[0u*Ncell+n]+=ux;  uSum[1u*Ncell+n]+=uy;  uSum[2u*Ncell+n]+=uz;
					u2Sum[0u*Ncell+n]+=ux*ux;  u2Sum[1u*Ncell+n]+=uy*uy;  u2Sum[2u*Ncell+n]+=uz*uz;
					slBuf[3u*n+0u]=ux;  slBuf[3u*n+1u]=uy;  slBuf[3u*n+2u]=uz; });
				{ FILE* fs=fopen("u_slice_y0.raw","ab"); const uint jy=Ny/2u; for(uint z=0u; z<Nz; z++) for(uint x=0u; x<Nx; x++) { const ulong n=((ulong)z*Ny+jy)*Nx+(ulong)x; fwrite(slBuf+3u*n, 12u, 1u, fs); } fclose(fs); } // y=物理中面 (jy=Ny/2, 非 y 下标 0=域边缘固体层!)
				{ FILE* fs=fopen("u_slice_zm.raw","ab"); const uint zm=Nz/2u; for(uint y=0u; y<Ny; y++) for(uint x=0u; x<Nx; x++) { const ulong n=((ulong)zm*Ny+y)*Nx+(ulong)x; fwrite(slBuf+3u*n, 12u, 1u, fs); } fclose(fs); } // z=mid 水平切片
				if(nAvg==0ull) { double dg1=0.0, dg2=0.0; for(ulong n=0ull; n<Ncell; n++) { dg1+=(double)uSum[0u*Ncell+n]; dg2+=(double)slBuf[3u*n]; } print_info("DIAG uSum="+to_string(dg1)+" slBuf="+to_string(dg2)); } // 一次性诊断
				nAvg++;
			}
		}
		lbm.update_fields();
		lbm.update_force_field();
		lbm.F.write_device_to_vtk("vtk/F_"+to_string(lbm.get_t())); // 表面气动载荷 (表面着色/压差分析用)
		lbm.rho.write_device_to_vtk("vtk/rho_"+to_string(lbm.get_t()));
		lbm.u.write_device_to_vtk("vtk/u_"+to_string(lbm.get_t()));
		print_info("snapshot at t="+to_string(lbm.get_t()));
	}
	if(nAvg>0ull) { // 时均/湍流度落盘: mean_u.vtk (矢量, 晶格单位) + tu.vtk (标量, 百分数)
		float* meanBuf = new float[3u*Ncell];  float* tuBuf = new float[Ncell];
		float sMin=1e30f, sMax=0.0f, tuMax=0.0f;
		for(ulong n=0ull; n<Ncell; n++) {
			const float mx=uSum[0u*Ncell+n]/(float)nAvg, my=uSum[1u*Ncell+n]/(float)nAvg, mz=uSum[2u*Ncell+n]/(float)nAvg;
			meanBuf[3u*n+0u]=mx;  meanBuf[3u*n+1u]=my;  meanBuf[3u*n+2u]=mz;
			const float v2 = fmaxf(u2Sum[0u*Ncell+n]/(float)nAvg-mx*mx,0.0f)+fmaxf(u2Sum[1u*Ncell+n]/(float)nAvg-my*my,0.0f)+fmaxf(u2Sum[2u*Ncell+n]/(float)nAvg-mz*mz,0.0f);
			const float tu = 100.0f*sqrtf(v2)/uLx;  tuBuf[n]=tu;  if(tu>tuMax) tuMax=tu;
			const float sm2 = mx*mx+my*my+mz*mz;  if(sm2<sMin) sMin=sm2;  if(sm2>sMax) sMax=sm2;
		}
		writeVTK("vtk/mean_u.vtk", meanBuf, 3u);
		writeVTK("vtk/tu.vtk", tuBuf, 1u);
		print_info("time-avg: "+to_string((unsigned long long)nAvg)+" samples | |U|mean "+to_string(velPhys*sqrtf(sMin))+".."+to_string(velPhys*sqrtf(sMax))+" m/s | Tu max "+to_string(tuMax)+"%");
		delete[] meanBuf;  delete[] tuBuf;
	}
	delete[] uSum;  delete[] u2Sum;  delete[] slBuf;
	delete[] raw;
	print_info("wind tunnel done - see vtk/ and forces.csv");
}
