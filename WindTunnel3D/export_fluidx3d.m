%% export_fluidx3d — MATLAB 风洞 → FluidX3D GPU 求解衔接器
% 流程: tunnel_voxelize 体素化(涵道+STL测试物) → windtunnel.raw
%       + 生成 setup_windtunnel.cpp (读raw/进出口TYPE_E/VTK输出)
%       + build_windtunnel.bat (用已装 MSVC 编译)
% 之后: 运行 windtunnel.exe 即 GPU 求解; VTK 用 ParaView 查看
clear; clc;
P = tunnel_params();
if getenv('WT_OBJ'), P.lbm.object = getenv('WT_OBJ'); end   % 命令行覆盖测试物 (与 lbm_run 一致)
if strcmpi(P.lbm.object,'stl') && ~exist(P.lbm.objFile,'file')
    fprintf('[提示] 未找到 %s, 测试物退回 sphere (放入 STL 后重跑即用你的模型)\n', P.lbm.objFile);
    P.lbm.object = 'sphere';
end

%% ---- GPU 档位 (RX 6650 XT 8GB 甜点: 2mm 晶格) ----
GPU = 'full';
if ~isempty(getenv('WT_QUICK')), GPU = 'smoke'; end
switch GPU
    case 'smoke', dxg = 0.006; nSteps = 3000;  nSnap = 750;    % ~1 分钟冒烟
    otherwise,    dxg = 0.002; nSteps = 30000; nSnap = 1500;   % 全档: 20 快照 (时均/湍流度统计)
end
dxEnv = getenv('WT_DX');
if ~isempty(dxEnv) && isfinite(str2double(dxEnv))            % 晶格覆盖 (1mm 档: WT_DX=0.001)
    dxg = min(0.01, max(0.0005, str2double(dxEnv)));
    fprintf('[WT_DX] 晶格覆盖: %.2f mm (格数与耗时按 dx 三~四次方涨)\n', dxg*1e3);
end
noObj = ~isempty(getenv('WT_NOOBJ'));   % 空风洞基线模式: 被测物几何仍测算但不写入流场
avgSfx = '';  if noObj, avgSfx = '_base'; end
nForces = 100;   % 力采样间隔 (步): 与 VTK 解耦, Cd/Cl 时程满足涡脱 Nyquist (St 可测)
nAvgStart = floor(nSteps/2);   % 时均统计起点 (步): 剔除初始瞬态
P.lbm.dx = dxg;
% 入口合成湍流度: Tu 链 (与 flow3d_solve 同式) — 风扇后 10% → 蜂窝器 ×0.65 → 纱网 (1/2)^n → 收缩 R^-0.7
tuIn = 0.10 * 0.65 * 0.5^P.sc.nScreen * P.ct.R^-0.7;

%% ---- 体素化 ----
G = tunnel_geometry(P);
[solid, obj, grid] = tunnel_voxelize(P, G);
nx = grid.nx; ny = grid.ny; nz = grid.nz;
fprintf('GPU 网格: %dx%dx%d = %.1fM 格 (dx=%.1fmm)\n', nx,ny,nz, nx*ny*nz/1e6, dxg*1e3);

%% ---- 被测物几何测算 (双重测算之"被测物"侧): 迎风面积/包围盒/堵塞比 ----
objBBox = [0 0 0];  Afr = NaN;
if any(obj(:))
    [ii0,jj0,kk0] = ind2sub([nx,ny,nz], find(obj));
    objBBox = [max(grid.x(ii0))-min(grid.x(ii0)), max(grid.y(jj0))-min(grid.y(jj0)), ...
               max(grid.z(kk0))-min(grid.z(kk0))];
    Afr = nnz(max(obj,[],1))*dxg^2;    % 沿流向投影到 y-z 平面的迎风面积 (Cd 参考)
end
blk = Afr/(P.ts.W*P.ts.H)*100;
fprintf('被测物: 包围盒 %.0fx%.0fx%.0f mm (最窄 %.0fmm = %.1f 格) | 迎风面积 %.1f cm² | 堵塞比 %.1f%%', ...
    objBBox(1)*1e3, objBBox(2)*1e3, objBBox(3)*1e3, min(objBBox)*1e3, min(objBBox)/dxg, Afr*1e4, blk);
if isnan(Afr), fprintf(' [!] 无被测物体素!\n');
elseif blk > 25, fprintf(' [!] 高堵塞: 局部加速大, LBM 裕度下降, Cd 仅作相对比较\n');
elseif blk > 10, fprintf(' [!] 堵塞偏高 (常规风洞建议 <10%%): Cd 绝对值偏大\n');
else, fprintf(' (堵塞比正常)\n');
end

% 归档旧一代 VTK 结果: 与 raw/meta 严格配套, 混用两代会尺寸错乱
vtkDir = fullfile(pwd,'fluidx3d','vtk');
if exist(vtkDir,'dir')
    dOld = [dir(fullfile(vtkDir,'u_*.vtk')); dir(fullfile(vtkDir,'rho_*.vtk')); dir(fullfile(vtkDir,'F_*.vtk'))];
    nMT = 0;
    for fN = {'mean_u.vtk','tu.vtk'}
        if isfile(fullfile(vtkDir,fN{1})), nMT = nMT + 1; end
    end
    if ~isempty(dOld) || nMT > 0
        prevDir = fullfile(pwd,'fluidx3d','vtk_prev');
        if ~exist(prevDir,'dir'), mkdir(prevDir); end
        for pat = {'u_*.vtk','rho_*.vtk','F_*.vtk','u_slice_*.raw'}   % 通配符空匹配时 movefile 会报错, 先查再移
            dd = dir(fullfile(vtkDir,pat{1}));
            if ~isempty(dd), movefile(fullfile(vtkDir,pat{1}), prevDir); end
        end
        for fN = {'mean_u.vtk','tu.vtk'}
            if isfile(fullfile(vtkDir,fN{1})), movefile(fullfile(vtkDir,fN{1}), prevDir); end
        end
        fprintf('旧一代 VTK 结果 %d 个已归档至 fluidx3d\\vtk_prev\\ (几何/参数变更后旧结果作废)\n', numel(dOld)+nMT);
    end
end

%% ---- 单位换算 (晶格 ↔ 物理) ----
U = P.V_test; uLx = 0.08;                     % 晶格来流 (Ma 0.14)
% 名义晶格 Re = P.lbm.Re (以试验段宽度计) — 受 LBM 松弛稳定下限约束;
% 高 Re 湍流行为由 FluidX3D 内置 SUBGRID LES (Smagorinsky) 补足有效粘度,
% 求解的物理行为相当于高 Re LES, 但名义 Re 不等于物理 Re (~5e5)
nuL = uLx*(P.ts.W/dxg)/P.lbm.Re;              % 晶格粘度
dtP = uLx*dxg/U;                              % 晶格步 → 物理秒
dxP = dxg;                                     % 晶格长 → 物理米
fprintf('晶格: u=%.3f, nu=%.4f (Re=%d) | dt=%.2e s, dx=%.1f mm\n', ...
    uLx, nuL, round(uLx*(P.ts.W/dxg)/nuL), dtP, dxP*1e3);

%% ---- 写 RAW 体素文件 (0=流体 1=涵道壁 2=测试物; x 最快, 与 FluidX3D index 一致) ----
raw = zeros(nx,ny,nz,'uint8');
raw(solid) = 1;
if noObj
    fprintf('[基准模式 WT_NOOBJ] 被测物几何已测算但不写入流场 (空风洞基线; 之后请重跑不带 WT_NOOBJ 的 export)\n');
else
    raw(obj) = 2;
end
fid = fopen(fullfile(pwd,'windtunnel.raw'),'wb');
fwrite(fid, raw, 'uint8');  fclose(fid);
fprintf('windtunnel.raw 已写 (%.1f MB)\n', numel(raw)/2^20);

%% ---- 生成 setup_windtunnel.cpp ----
% 快照 VTK 输出档位: WT_VTK='u' (默认, 只写 u 场, 省 ~2/3 磁盘与写盘停顿) | 'all' (u+rho+F, F 供表面着色)
% [2026-09-30 修复] 快照前不再调用 lbm.update_fields(): 本配置下该内核对镜像的重构损坏
%   (实测 rho 0.61~2.02、u 流体区低 ~8 倍); 主内核每步已维护真实镜像, 直接写即真实流场
vtkAll = ~isempty(getenv('WT_VTK')) && strcmpi(getenv('WT_VTK'), 'all');
vtkExtra = '';
if vtkAll
    l1 = '\t\tlbm.rho.write_device_to_vtk("vtk/rho_"+to_string(lbm.get_t()));\n';
    l2 = '\t\tlbm.F.write_device_to_vtk("vtk/F_"+to_string(lbm.get_t())); // surface loads\n';
    vtkExtra = [sprintf(l1), sprintf(l2)];
end
src = [ ...
'\#include "setup.hpp"' sprintf('\n') ...
sprintf('void main_setup() { // auto-generated by export_fluidx3d.m (dx=%.1fmm, dt=%.2es)\n', dxP*1e3, dtP) ...
sprintf('	LBM lbm(%du, %du, %du, %.6ff); // grid + lattice viscosity\n', nx, ny, nz, nuL) ...
sprintf('	const uint Nx=lbm.get_Nx(), Ny=lbm.get_Ny(), Nz=lbm.get_Nz();\n') ...
sprintf('	// ---- read voxel file: 0=fluid 1=wall 2=test object (x-fastest order) ----\n') ...
sprintf('	uchar* raw = new uchar[lbm.get_N()];\n') ...
sprintf('	{ FILE* f=fopen("windtunnel.raw","rb");\n') ...
sprintf('	  if(!f) { print_error("windtunnel.raw not found"); exit(1); }\n') ...
sprintf('	  if(fread(raw, 1, lbm.get_N(), f)!=lbm.get_N()) { print_error("raw size mismatch"); exit(1); } fclose(f); }\n') ...
sprintf('	parallel_for(lbm.get_N(), [&](ulong n) {\n') ...
sprintf('		lbm.flags[n] = raw[n]==0u ? 0u : (raw[n]==2u ? (TYPE_S|TYPE_X) : TYPE_S); // 流体=0(默认), 测试物=S|X 单独标记\n') ...
sprintf('	});\n') ...
sprintf('	// ---- inlet x=0 / outlet x=Nx-1: equilibrium boundaries ----\n') ...
sprintf('	parallel_for(lbm.get_N(), [&](ulong n) { uint x=0u, y=0u, z=0u; lbm.coordinates(n, x, y, z);\n') ...
sprintf('		if(x==0u)          { lbm.flags[n]=TYPE_E; lbm.rho[n]=1.0f; lbm.u.x[n]=%.5ff; lbm.u.y[n]=0.0f; lbm.u.z[n]=0.0f; }\n', uLx) ...
sprintf('		if(x==Nx-1u)       { lbm.flags[n]=TYPE_E; lbm.rho[n]=1.0f; lbm.u.x[n]=%.5ff; lbm.u.y[n]=0.0f; lbm.u.z[n]=0.0f; } // outlet: moving reservoir\n', uLx) ...
sprintf('	});\n') ...
sprintf('	// ---- 入口合成湍流 + 逐步时均/湍流度统计 + 力时程 ----\n') ...
sprintf('	const float uLx = %.5ff, velPhys = %.4ff; // 晶格来流 / 晶格->物理速度\n', uLx, U/uLx) ...
sprintf('	const float tuInl = %.5ff; // 入口合成湍流度 (Tu 链: 蜂窝器+纱网+收缩段衰减)\n', tuIn) ...
sprintf('	const ulong nAvgStart = %du; // 时均起点步 (剔除初始瞬态)\n', nAvgStart) ...
sprintf('	const ulong Ncell = lbm.get_N();\n') ...
sprintf('	float* uSum = new float[3u*Ncell]();  float* u2Sum = new float[3u*Ncell](); // sum(u), sum(u^2), SoA: [c*Ncell+n]\n') ...
sprintf('	float* slBuf = new float[3u*Ncell]; // 切片流暂存 (与 uSum 同源读取路径, 时均块内采样)\n') ...
sprintf('	ulong nAvg = 0ull;  uint rngS = 987654321u;\n') ...
sprintf('	auto rnd01 = [&]() { rngS^=rngS<<13u; rngS^=rngS>>17u; rngS^=rngS<<5u; return (float)(rngS&0xFFFFFFu)/16777216.0f; };\n') ...
sprintf('	auto writeVTK = [&](const string& fname, const float* data, const uint ncomp) { // 大端 VTK (与 FluidX3D 输出同格式)\n') ...
sprintf('		FILE* f = fopen(fname.c_str(), "wb");  if(!f) { print_error("cannot write "+fname); return; }\n') ...
sprintf('		char hdr[512];\n') ...
sprintf('		sprintf(hdr, "# vtk DataFile Version 3.0\\nWindTunnel3D %%s\\nBINARY\\nDATASET STRUCTURED_POINTS\\nDIMENSIONS %%u %%u %%u\\nORIGIN %%.8E %%.8E %%.8E\\nSPACING 1.00000000 1.00000000 1.00000000\\nPOINT_DATA %%llu\\nSCALARS data float %%u\\nLOOKUP_TABLE default\\n", fname.c_str(), Nx, Ny, Nz, -0.5*(double)(Nx-1u), -0.5*(double)(Ny-1u), -0.5*(double)(Nz-1u), (unsigned long long)Ncell, ncomp);\n') ...
sprintf('		fputs(hdr, f);\n') ...
sprintf('		float* buf = new float[Ncell*ncomp];\n') ...
sprintf('		parallel_for(Ncell*ncomp, [&](ulong n) { union { float f; unsigned int u; } v; v.f = data[n]; v.u = (v.u>>24u)|((v.u>>8u)&0xFF00u)|((v.u<<8u)&0xFF0000u)|(v.u<<24u); buf[n] = v.f; }); // 字节序翻转 (VTK 经典二进制为大端)\n') ...
sprintf('		fwrite(buf, 4u*Ncell*ncomp, 1u, f);  fclose(f);  delete[] buf;\n') ...
sprintf('		print_info("File \\""+fname+"\\" saved.");\n') ...
sprintf('	};\n') ...
sprintf('	auto gustUpdate = [&]() { // 入口合成湍流: 流函数法 y-z 面横向涡旋脉动 (严格无散, 可输运到下游)\n') ...
sprintf('		float ky[6], kz[6], ph[6];  float sky=0.0f, skz=0.0f;\n') ...
sprintf('		for(uint q=0u; q<6u; q++) {\n') ...
sprintf('			ky[q] = 6.2831853f*(rnd01()<0.5f?-1.0f:1.0f)/(20.0f+60.0f*rnd01()); // 波长 20~80 格 (大涡, 抗耗散)\n') ...
sprintf('			kz[q] = 6.2831853f*(rnd01()<0.5f?-1.0f:1.0f)/(20.0f+60.0f*rnd01());\n') ...
sprintf('			ph[q] = 6.2831853f*rnd01();\n') ...
sprintf('			sky += ky[q]*ky[q];  skz += kz[q]*kz[q];\n') ...
sprintf('		}\n') ...
sprintf('		const float Ay = tuInl*uLx*sqrtf(2.0f/skz), Az = tuInl*uLx*sqrtf(2.0f/sky); // 精确归一: 每分量 rms = tuInl*uLx\n') ...
sprintf('		for(uint z=0u; z<Nz; z++) for(uint y=0u; y<Ny; y++) {\n') ...
sprintf('			const ulong n = (z*(ulong)Ny+(ulong)y)*(ulong)Nx;\n') ...
sprintf('			float gy=0.0f, gz=0.0f;\n') ...
sprintf('			for(uint m=0u; m<6u; m++) { const float sy=(float)y, sz=(float)z, cs=cosf(ky[m]*sy+kz[m]*sz+ph[m]);\n') ...
sprintf('				gy += kz[m]*cs;  gz += -ky[m]*cs; } // psi=sum sin, u=(dpsi/dz, -dpsi/dy): div-free\n') ...
sprintf('			lbm.u.x[n] = uLx;  lbm.u.y[n] = Ay*gy;  lbm.u.z[n] = Az*gz;\n') ...
sprintf('		}\n') ...
sprintf('		lbm.u.write_to_device();\n') ...
sprintf('	};\n') ...
sprintf('	{ FILE* fc=fopen("forces.csv","w"); fprintf(fc, "t_lattice,Fx,Fy,Fz\\n"); fclose(fc); }\n') ...
sprintf('	const float Fscale = %.6ff; // lattice -> Newton  (rho*dx^4/dt^2)\n', P.rho*dxP^4/dtP^2) ...
sprintf('	const float Tscale = %.6ef; // lattice step -> seconds\n', dtP) ...
sprintf('	gustUpdate(); // 首个入口脉动 (run() 首次调用时以此初始化流场)\n') ...
sprintf('	for(uint s=0u; s<%du; s+=%du) {\n', nSteps, nSnap) ...
sprintf('		for(uint ss=0u; ss<%du; ss+=%du) { // 力采样+入口湍流相位更新: 每 %d 步 (涡脱 Nyquist, 与 VTK 解耦)\n', nSnap, nForces, nForces) ...
sprintf('			gustUpdate();\n') ...
sprintf('			lbm.run(%du, %du);\n', nForces, nSteps) ...
sprintf('			lbm.update_force_field();\n') ...
sprintf('			const float3 F = lbm.object_force(TYPE_S|TYPE_X); // 仅测试物 (整字节匹配)\n') ...
sprintf('			{ FILE* fc=fopen("forces.csv","a"); fprintf(fc, "%%u,%%g,%%g,%%g\\n", lbm.get_t(), F.x*Fscale, F.y*Fscale, F.z*Fscale); fclose(fc); }\n') ...
sprintf('			if(lbm.get_t()>=nAvgStart) { // 逐步时均累加 (无欠采样) + 切片流采样 (与 uSum 同一 parallel_for 读取路径, 已由 mean_u 验证)\n') ...
sprintf('				lbm.u.read_from_device();\n') ...
sprintf('				parallel_for(Ncell, [&](ulong n) { const float ux=lbm.u.x[n], uy=lbm.u.y[n], uz=lbm.u.z[n];\n') ...
sprintf('					uSum[0u*Ncell+n]+=ux;  uSum[1u*Ncell+n]+=uy;  uSum[2u*Ncell+n]+=uz;\n') ...
sprintf('					u2Sum[0u*Ncell+n]+=ux*ux;  u2Sum[1u*Ncell+n]+=uy*uy;  u2Sum[2u*Ncell+n]+=uz*uz;\n') ...
sprintf('					slBuf[3u*n+0u]=ux;  slBuf[3u*n+1u]=uy;  slBuf[3u*n+2u]=uz; });\n') ...
sprintf('				{ FILE* fs=fopen("u_slice_y0.raw","ab"); const uint jy=Ny/2u; for(uint z=0u; z<Nz; z++) for(uint x=0u; x<Nx; x++) { const ulong n=((ulong)z*Ny+jy)*Nx+(ulong)x; fwrite(slBuf+3u*n, 12u, 1u, fs); } fclose(fs); } // y=物理中面 (jy=Ny/2, 非 y 下标 0=域边缘固体层!)\n') ...
sprintf('				{ FILE* fs=fopen("u_slice_zm.raw","ab"); const uint zm=Nz/2u; for(uint y=0u; y<Ny; y++) for(uint x=0u; x<Nx; x++) { const ulong n=((ulong)zm*Ny+y)*Nx+(ulong)x; fwrite(slBuf+3u*n, 12u, 1u, fs); } fclose(fs); } // z=mid 水平切片\n') ...
sprintf('				if(nAvg==0ull) { double dg1=0.0, dg2=0.0; for(ulong n=0ull; n<Ncell; n++) { dg1+=(double)uSum[0u*Ncell+n]; dg2+=(double)slBuf[3u*n]; } print_info("DIAG uSum="+to_string(dg1)+" slBuf="+to_string(dg2)); } // 一次性诊断\n') ...
sprintf('				nAvg++;\n') ...
sprintf('			}\n') ...
sprintf('		}\n') ...
sprintf('		lbm.update_force_field();\n') ...
sprintf('		lbm.u.write_device_to_vtk("vtk/u_"+to_string(lbm.get_t()));\n') ...
vtkExtra ...
sprintf('		print_info("snapshot at t="+to_string(lbm.get_t()));\n') ...
sprintf('	}\n') ...
sprintf('	if(nAvg>0ull) { // 时均/湍流度落盘: mean_u.vtk (矢量, 晶格单位) + tu.vtk (标量, 百分数)\n') ...
sprintf('		float* meanBuf = new float[3u*Ncell];  float* tuBuf = new float[Ncell];\n') ...
sprintf('		float sMin=1e30f, sMax=0.0f, tuMax=0.0f;\n') ...
sprintf('		for(ulong n=0ull; n<Ncell; n++) {\n') ...
sprintf('			const float mx=uSum[0u*Ncell+n]/(float)nAvg, my=uSum[1u*Ncell+n]/(float)nAvg, mz=uSum[2u*Ncell+n]/(float)nAvg;\n') ...
sprintf('			meanBuf[3u*n+0u]=mx;  meanBuf[3u*n+1u]=my;  meanBuf[3u*n+2u]=mz;\n') ...
sprintf('			const float v2 = fmaxf(u2Sum[0u*Ncell+n]/(float)nAvg-mx*mx,0.0f)+fmaxf(u2Sum[1u*Ncell+n]/(float)nAvg-my*my,0.0f)+fmaxf(u2Sum[2u*Ncell+n]/(float)nAvg-mz*mz,0.0f);\n') ...
sprintf('			const float tu = 100.0f*sqrtf(v2)/uLx;  tuBuf[n]=tu;  if(tu>tuMax) tuMax=tu;\n') ...
sprintf('			const float sm2 = mx*mx+my*my+mz*mz;  if(sm2<sMin) sMin=sm2;  if(sm2>sMax) sMax=sm2;\n') ...
sprintf('		}\n') ...
sprintf('		writeVTK("vtk/mean_u%s.vtk", meanBuf, 3u);\n', avgSfx) ...
sprintf('		writeVTK("vtk/tu%s.vtk", tuBuf, 1u);\n', avgSfx) ...
sprintf('		print_info("time-avg: "+to_string((unsigned long long)nAvg)+" samples | |U|mean "+to_string(velPhys*sqrtf(sMin))+".."+to_string(velPhys*sqrtf(sMax))+" m/s | Tu max "+to_string(tuMax)+"%%");\n') ...
sprintf('		delete[] meanBuf;  delete[] tuBuf;\n') ...
sprintf('	}\n') ...
	sprintf('	delete[] uSum;  delete[] u2Sum;  delete[] slBuf;\n') ...
sprintf('	delete[] raw;\n') ...
sprintf('	print_info("wind tunnel done - see vtk/ and forces.csv");\n') ...
sprintf('}\n')];
fid = fopen(fullfile(pwd,'setup_windtunnel.cpp'),'w');
fprintf(fid, '%s', strrep(src, '\#', '#'));
fclose(fid);
if ~exist(fullfile(pwd,'vtk'),'dir'), mkdir(fullfile(pwd,'vtk')); end
fprintf('setup_windtunnel.cpp 已生成 (%d 步, 每 %d 步 VTK 快照 + 每 %d 步力采样/入口湍流更新 + 逐步时均)\n', nSteps, nSnap, nForces);

% 元数据 (explore_gpu 读回用); STL 的 Aref 用真实迎风投影面积 (参数化物体用解析式)
ArefUse = refAreaG(P);  if isfinite(Afr), ArefUse = Afr; end
meta = struct('dx',dxP, 'dt',dtP, 'velScale',U/uLx, 'nx',nx, 'ny',ny, 'nz',nz, ...
    'V_test',U, 'rho',P.rho, 'Aref',ArefUse, 'tSnap_lattice',nSnap, 'nSteps',nSteps, ...
    'ReLattice', round(uLx*(P.ts.W/dxg)/nuL), ...   % 名义晶格 Re (LES 有效高 Re, 见上注)
